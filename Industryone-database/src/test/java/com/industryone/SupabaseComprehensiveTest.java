    @Test
    @Order(1)
    void testCreateTablesAndMigrateOnSupabase() throws Exception {
        System.out.println("\n--- [1/6] RUNNING SUPABASE MIGRATION: 3 DEDICATED TABLES ---");
        try (Connection conn = dataSource.getConnection();
             Statement stmt = conn.createStatement()) {

            // 1. Create admin_users
            stmt.execute("""
                CREATE TABLE IF NOT EXISTS public.admin_users (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    email VARCHAR(255) NOT NULL UNIQUE,
                    password_hash VARCHAR(255) NOT NULL,
                    full_name VARCHAR(255) NOT NULL,
                    department VARCHAR(255) NOT NULL DEFAULT 'National Directorate',
                    active BOOLEAN NOT NULL DEFAULT TRUE,
                    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
                );
            """);

            // 2. Create officer_users
            stmt.execute("""
                CREATE TABLE IF NOT EXISTS public.officer_users (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    email VARCHAR(255) NOT NULL UNIQUE,
                    password_hash VARCHAR(255) NOT NULL,
                    full_name VARCHAR(255) NOT NULL,
                    department VARCHAR(255) NOT NULL DEFAULT 'General Scrutiny Directorate',
                    desk_id VARCHAR(100),
                    active BOOLEAN NOT NULL DEFAULT TRUE,
                    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
                );
            """);

            // 3. Create applicant_users
            stmt.execute("""
                CREATE TABLE IF NOT EXISTS public.applicant_users (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    email VARCHAR(255) NOT NULL UNIQUE,
                    password_hash VARCHAR(255) NOT NULL,
                    full_name VARCHAR(255) NOT NULL,
                    business_name VARCHAR(255),
                    mobile VARCHAR(20),
                    active BOOLEAN NOT NULL DEFAULT TRUE,
                    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
                );
            """);

            // 4. Update auth_tokens structure
            stmt.execute("""
                CREATE TABLE IF NOT EXISTS public.auth_tokens (
                    token VARCHAR(100) PRIMARY KEY,
                    user_id BIGINT NOT NULL,
                    role VARCHAR(50) NOT NULL,
                    email VARCHAR(255) NOT NULL,
                    full_name VARCHAR(255) NOT NULL,
                    expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
                );
            """);
            stmt.execute("ALTER TABLE public.auth_tokens DROP CONSTRAINT IF EXISTS fk_auth_tokens_user;");
            stmt.execute("ALTER TABLE public.auth_tokens ADD COLUMN IF NOT EXISTS role VARCHAR(50) DEFAULT 'USER';");
            stmt.execute("ALTER TABLE public.auth_tokens ADD COLUMN IF NOT EXISTS email VARCHAR(255) DEFAULT '';");
            stmt.execute("ALTER TABLE public.auth_tokens ADD COLUMN IF NOT EXISTS full_name VARCHAR(255) DEFAULT '';");


            // 5. Ensure indexes
            stmt.execute("CREATE INDEX IF NOT EXISTS idx_admin_users_email ON public.admin_users (LOWER(email));");
            stmt.execute("CREATE INDEX IF NOT EXISTS idx_officer_users_email ON public.officer_users (LOWER(email));");
            stmt.execute("CREATE INDEX IF NOT EXISTS idx_applicant_users_email ON public.applicant_users (LOWER(email));");

            // 6. Migrate from legacy 'users' table if it exists
            try {
                stmt.execute("""
                    INSERT INTO public.admin_users (email, password_hash, full_name, active)
                    SELECT email, password_hash, full_name, active FROM public.users
                    WHERE role = 'ADMIN'
                    ON CONFLICT (email) DO NOTHING;
                """);

                stmt.execute("""
                    INSERT INTO public.officer_users (email, password_hash, full_name, active)
                    SELECT email, password_hash, full_name, active FROM public.users
                    WHERE role = 'OFFICER'
                    ON CONFLICT (email) DO NOTHING;
                """);

                stmt.execute("""
                    INSERT INTO public.applicant_users (email, password_hash, full_name, active)
                    SELECT email, password_hash, full_name, active FROM public.users
                    WHERE role = 'ENTREPRENEUR'
                    ON CONFLICT (email) DO NOTHING;
                """);
                System.out.println("  Migrated legacy records from 'users' into 3 dedicated tables.");
            } catch (Exception ignored) {
                // Ignore if legacy users table is not present
            }

            System.out.println("  [PASS] Successfully verified and applied 3 tables on Supabase!");
        }
    }

