    @Test
    @Order(3)
    void testAuthenticationAcrossThreeTables() {
        System.out.println("\n--- [3/6] TESTING AUTHENTICATION ROUTING TO RESPECTIVE TABLES ---");

        // Admin login -> checks admin_users
        Optional<User> admin = userService.authenticate("admin@industryone.gov.in", "Admin@12345", "ADMIN");
        assertTrue(admin.isPresent(), "Admin auth should succeed against admin_users");
        assertEquals("ADMIN", admin.get().getRole());
        System.out.println("  [PASS] Admin authenticated from admin_users: " + admin.get().getFullName());

        // Officer login -> checks officer_users
        Optional<User> officer = userService.authenticate("officer@industryone.gov.in", "Officer@12345", "OFFICER");
        assertTrue(officer.isPresent(), "Officer auth should succeed against officer_users");
        assertEquals("OFFICER", officer.get().getRole());
        System.out.println("  [PASS] Officer authenticated from officer_users: " + officer.get().getFullName());

        // Applicant login -> checks applicant_users
        Optional<User> applicant = userService.authenticate("entrepreneur@example.com", "Entrepreneur@12345", "ENTREPRENEUR");
        assertTrue(applicant.isPresent(), "Applicant auth should succeed against applicant_users");
        assertEquals("ENTREPRENEUR", applicant.get().getRole());
        System.out.println("  [PASS] Applicant authenticated from applicant_users: " + applicant.get().getFullName());

        // Cross-role failure check: Admin email with OFFICER role should fail
        Optional<User> wrongRole = userService.authenticate("admin@industryone.gov.in", "Admin@12345", "OFFICER");
        assertTrue(wrongRole.isEmpty(), "Cross-role login must be rejected");
        System.out.println("  [PASS] Cross-role login rejected properly");
    }

    @Test
    @Order(4)
    void testApplicantRegistrationInApplicantUsers() {
        System.out.println("\n--- [4/6] TESTING REGISTRATION PERSISTS IN APPLICANT_USERS ---");
        String testEmail = "test_applicant_" + System.currentTimeMillis() + "@startup.in";

        User registered = userService.createUser(testEmail, "Startup@2026!", "ENTREPRENEUR", "Ananya Singhal");
        assertNotNull(registered.getId());
        assertEquals(testEmail, registered.getEmail());
        assertEquals("ENTREPRENEUR", registered.getRole());

        // Verify it was persisted in applicant_users table specifically
        Optional<ApplicantUser> inDb = applicantUserRepository.findByEmailIgnoreCase(testEmail);
        assertTrue(inDb.isPresent(), "Newly registered applicant must exist in applicant_users");
        assertEquals("Ananya Singhal", inDb.get().getFullName());
        System.out.println("  [PASS] New applicant saved in applicant_users table (ID: " + inDb.get().getId() + ")");

        // Clean up test applicant
        applicantUserRepository.delete(inDb.get());
    }

    @Test
    @Order(5)
    void testAuthTokenMultiTableSupport() {
        System.out.println("\n--- [5/6] TESTING SESSION TOKENS FOR MULTI-TABLE USERS ---");
        User admin = userService.authenticate("admin@industryone.gov.in", "Admin@12345", "ADMIN").orElseThrow();
        String adminToken = authService.createToken(admin);
        assertNotNull(adminToken);

        Optional<User> resolvedAdmin = authService.getUser(adminToken);
        assertTrue(resolvedAdmin.isPresent());
        assertEquals("admin@industryone.gov.in", resolvedAdmin.get().getEmail());
        assertEquals("ADMIN", resolvedAdmin.get().getRole());
        System.out.println("  [PASS] Token resolved Admin correctly: " + resolvedAdmin.get().getEmail());

        User applicant = userService.authenticate("entrepreneur@example.com", "Entrepreneur@12345", "ENTREPRENEUR").orElseThrow();
        String applicantToken = authService.createToken(applicant);
        assertNotNull(applicantToken);

        Optional<User> resolvedApplicant = authService.getUser(applicantToken);
        assertTrue(resolvedApplicant.isPresent());
        assertEquals("entrepreneur@example.com", resolvedApplicant.get().getEmail());
        assertEquals("ENTREPRENEUR", resolvedApplicant.get().getRole());
        System.out.println("  [PASS] Token resolved Applicant correctly: " + resolvedApplicant.get().getEmail());

        authService.logout(adminToken);
        authService.logout(applicantToken);
    }

