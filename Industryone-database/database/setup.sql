-- =============================================================================
-- IndustryOne - Database Setup Script (Supabase / PostgreSQL)
-- Three Dedicated Tables for User Logins:
-- 1. admin_users     -> Department Heads & Directorate Admins
-- 2. officer_users   -> Verification Officers & Scrutiny Desks
-- 3. applicant_users -> Entrepreneurs & Industrial Applicants
-- =============================================================================
-- For SUPABASE:
-- 1. Open Supabase Dashboard -> "SQL Editor" -> "+ New query".
-- 2. Paste the contents of this file and click "Run".
-- =============================================================================

-- Enable pgcrypto for cryptography and BCrypt hashing
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- -----------------------------------------------------------------------------
-- 1. Table: admin_users (Admin Portal Logins)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.admin_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    department VARCHAR(255) NOT NULL DEFAULT 'National Directorate',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- -----------------------------------------------------------------------------
-- 2. Table: officer_users (Verification Officer Portal Logins)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.officer_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    department VARCHAR(255) NOT NULL DEFAULT 'General Scrutiny Directorate',
    desk_id VARCHAR(100),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- -----------------------------------------------------------------------------
-- 3. Table: applicant_users (Applicant & Entrepreneur Logins / Registrations)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.applicant_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    business_name VARCHAR(255),
    mobile VARCHAR(20),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- -----------------------------------------------------------------------------
-- 4. Table: auth_tokens (Decoupled Multi-Role Session Tokens)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.auth_tokens (
    token VARCHAR(100) PRIMARY KEY,
    user_id BIGINT NOT NULL,
    role VARCHAR(50) NOT NULL,
    email VARCHAR(255) NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

-- -----------------------------------------------------------------------------
-- 5. Table: login_attempts (Failed Attempts & Temporary Lockouts)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.login_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    role VARCHAR(50) NOT NULL,
    failed_attempts INTEGER NOT NULL DEFAULT 0,
    locked_until TIMESTAMP WITHOUT TIME ZONE,
    last_failed_at TIMESTAMP WITHOUT TIME ZONE,
    last_ip VARCHAR(255),
    CONSTRAINT uk_login_attempts_email_role UNIQUE (email, role)
);

-- -----------------------------------------------------------------------------
-- 6. Table: security_alerts (Security Incidents for Admin Resolution)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.security_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_type VARCHAR(100) NOT NULL,
    severity VARCHAR(50) NOT NULL,
    email VARCHAR(255) NOT NULL,
    role VARCHAR(50) NOT NULL,
    ip_address VARCHAR(255),
    message VARCHAR(1000) NOT NULL,
    attempts INTEGER NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    resolved BOOLEAN NOT NULL DEFAULT FALSE,
    resolved_by VARCHAR(255),
    resolved_at TIMESTAMP WITHOUT TIME ZONE
);

-- -----------------------------------------------------------------------------
-- Performance Indexes
-- -----------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_admin_users_email ON public.admin_users (LOWER(email));
CREATE INDEX IF NOT EXISTS idx_officer_users_email ON public.officer_users (LOWER(email));
CREATE INDEX IF NOT EXISTS idx_applicant_users_email ON public.applicant_users (LOWER(email));
CREATE INDEX IF NOT EXISTS idx_auth_tokens_lookup ON public.auth_tokens (token, expires_at);
CREATE INDEX IF NOT EXISTS idx_login_attempts_email_role ON public.login_attempts (LOWER(email), UPPER(role));
CREATE INDEX IF NOT EXISTS idx_security_alerts_unresolved ON public.security_alerts (resolved, created_at DESC);

-- -----------------------------------------------------------------------------
-- Permissions
-- -----------------------------------------------------------------------------
GRANT ALL ON TABLE public.admin_users TO postgres;
GRANT ALL ON TABLE public.officer_users TO postgres;
GRANT ALL ON TABLE public.applicant_users TO postgres;
GRANT ALL ON TABLE public.auth_tokens TO postgres;
GRANT ALL ON TABLE public.login_attempts TO postgres;
GRANT ALL ON TABLE public.security_alerts TO postgres;

